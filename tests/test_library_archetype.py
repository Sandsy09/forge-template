def test_gitignore_only_excludes_generated_version_file_in_vcs_mode() -> None:
    static_spec = parse_project_spec(_payload(packaging_mode="uv-build-static"))
    vcs_spec = parse_project_spec(_payload(packaging_mode="hatchling-vcs"))

    static_gitignore = next(
        item.content
        for item in render_project(static_spec).files
        if item.target == ".gitignore"
    ).decode()
    vcs_gitignore = next(
        item.content
        for item in render_project(vcs_spec).files
        if item.target == ".gitignore"
    ).decode()

    assert "credit_risk_utils/_version.py" not in static_gitignore
    assert "credit_risk_utils/_version.py" in vcs_gitignore


def test_smoke_test_imports_the_rendered_package() -> None:
    spec = parse_project_spec(_payload(packaging_mode="uv-build-static"))

    rendered = render_project(spec)
    smoke_test = next(
        item.content for item in rendered.files if item.target == "tests/test_smoke.py"
    ).decode()

    assert "from credit_risk_utils import __version__" in smoke_test


# --- map_legacy_library_answers against the real production schema ---------


@pytest.mark.parametrize(
    ("build_backend", "versioning_resolved", "packaging_mode"),
    [
        ("uv_build", "static", "uv-build-static"),
        ("hatchling", "static", "hatchling-static"),
        ("hatchling", "vcs", "hatchling-vcs"),
    ],
)
def test_legacy_mapping_rows_are_valid_choices_on_the_real_schema(
    build_backend: str, versioning_resolved: str, packaging_mode: str
) -> None:
    result = map_legacy_library_answers(
        {"build_backend": build_backend, "versioning_resolved": versioning_resolved}
    )
    assert result == {"packaging_mode": packaging_mode}

    library = next(d for d in discover_components() if d.id == "library")
    schema_choices = next(
        o.choices for o in library.options if o.name == "packaging_mode"
    )
    assert result["packaging_mode"] in schema_choices
